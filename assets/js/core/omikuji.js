/** 重み付きで運勢を選ぶ */
export function pickRank(rand = Math.random) {
  const total = RANKS.reduce((sum, r) => sum + r.weight, 0);
  let point = rand() * total;
  for (const rank of RANKS) {
    point -= rank.weight;
    if (point < 0) return rank;
  }
  return RANKS[RANKS.length - 1];
}

/**
 * くじを 1 回引く。
 * @param {Function} rand 0〜1 の乱数（テストでは固定値を渡す）
 * @param {number[]} recent 直近に出た占いの番号（続けて同じものを出さない）
 */
export function drawOmikuji(rand = Math.random, recent = []) {
  const rank = pickRank(rand);
  const avoid = new Set(recent);
  let index = Math.floor(rand() * FORTUNES.length) % FORTUNES.length;
  // 直近と重なったら、少しずらして別の言葉にする
  for (let step = 0; step < FORTUNES.length && avoid.has(index); step += 1) {
    index = (index + 1) % FORTUNES.length;
  }
  return { rank: rank.id, fortune: index, at: new Date().toISOString() };
}

/** 保存された記録を、表示できる形にする */
export function readOmikuji(record) {
  if (!record || typeof record !== 'object') return null;
  const index = Number(record.fortune);
  if (!Number.isInteger(index) || index < 0 || index >= FORTUNES.length) return null;
  return { rank: rankOf(record.rank), fortune: FORTUNES[index], at: record.at || null, index };
}
