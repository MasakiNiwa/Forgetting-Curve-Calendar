const OPEN_KEY = 'fcc.help.open';

/** 開いていた見出しを覚えておく（画面を離れても、次に開いたとき同じ形で読める） */
function readOpen() {
  try {
    const raw = window.localStorage.getItem(OPEN_KEY);
    const list = raw ? JSON.parse(raw) : null;
    return new Set(Array.isArray(list) ? list.filter((v) => typeof v === 'string') : ['start']);
  } catch {
    return new Set(['start']);
  }
}

function writeOpen(set) {
  try {
    window.localStorage.setItem(OPEN_KEY, JSON.stringify([...set]));
  } catch { /* 覚えられなくても読める */ }
}

